/**
 * Compiles every contract under `contracts/` with solc-js and writes
 * `build/contracts.ts`: one `{ abi, bytecode }` export per contract, with the
 * ABI `as const` so viem infers typed `read`/`write`/event helpers from it.
 *
 * The output records a hash of the sources and compiler settings. When neither
 * changed, compilation is skipped.
 */
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { join, relative } from "node:path";

import solc from "solc";

const root = join(import.meta.dirname, "..");
const sourcesDir = join(root, "contracts");
const outFile = join(root, "build", "contracts.ts");

const settings = {
  evmVersion: "cancun",
  optimizer: { enabled: true, runs: 100 },
  outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
};

const sources: Record<string, { content: string }> = {};
for (const entry of readdirSync(sourcesDir, { recursive: true })) {
  const path = join(sourcesDir, String(entry));
  if (!path.endsWith(".sol")) continue;
  sources[relative(root, path)] = { content: readFileSync(path, "utf8") };
}

const hash = createHash("sha256")
  .update(solc.version())
  .update(JSON.stringify({ settings, sources }))
  .digest("hex");
const hashLine = `// sources: ${hash}`;

if (
  existsSync(outFile) &&
  readFileSync(outFile, "utf8").split("\n")[1] === hashLine
) {
  process.exit(0);
}

const output = JSON.parse(
  solc.compile(JSON.stringify({ language: "Solidity", sources, settings }))
);

const diagnostics: { severity: string; formattedMessage: string }[] =
  output.errors ?? [];
for (const { formattedMessage } of diagnostics) {
  console.error(formattedMessage);
}
if (diagnostics.some(({ severity }) => severity === "error")) {
  process.exit(1);
}

const exports: string[] = [];
for (const [file, contracts] of Object.entries<any>(output.contracts)) {
  for (const [name, { abi, evm }] of Object.entries<any>(contracts)) {
    exports.push(
      `/** ${file}:${name} */\n` +
        `export const ${name} = {\n` +
        `  abi: ${JSON.stringify(abi)} as const,\n` +
        `  bytecode: "0x${evm.bytecode.object}" as const,\n` +
        `};`
    );
  }
}

mkdirSync(join(root, "build"), { recursive: true });
writeFileSync(
  outFile,
  [
    `// Generated by scripts/compile.ts (solc ${solc.version()}). Do not edit.`,
    hashLine,
    "",
    ...exports,
    "",
  ].join("\n")
);
console.log(
  `Compiled ${exports.length} contracts to ${relative(root, outFile)}`
);
